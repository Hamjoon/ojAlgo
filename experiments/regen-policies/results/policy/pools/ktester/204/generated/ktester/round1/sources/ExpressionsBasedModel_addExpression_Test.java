package org.ojalgo.optimisation;

import static org.junit.jupiter.api.Assertions.*;
import java.util.Set;
import java.util.stream.Collectors;
import java.lang.reflect.Field;
import java.util.HashMap;
import java.util.Map;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.ValueSource;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.Test;

@ExtendWith(MockitoExtension.class)
class ExpressionsBasedModel_addExpression_Test {

    private ExpressionsBasedModel model;

    @BeforeEach
    void setupBeforeEach() {
        // Use the default constructor – it creates a fresh model with default options.
        model = new ExpressionsBasedModel();
    }

    @AfterEach
    void teardownAfterEach() {
        // Help the GC; not strictly required but keeps the pattern consistent.
        model = null;
    }

    @Test
    void testAddExpressionCreatesExpressionWithDefaultName() {
        // First call – should create "EXPR0"
        Expression expr0 = model.addExpression();
        assertNotNull(expr0, "addExpression() must not return null");
        assertEquals("EXPR0", expr0.getName(), "First autogenerated name should be EXPR0");
        assertEquals(1, model.countExpressions(), "Model should contain exactly one expression after first add");
        // Second call – should create "EXPR1"
        Expression expr1 = model.addExpression();
        assertNotNull(expr1);
        assertEquals("EXPR1", expr1.getName(), "Second autogenerated name should be EXPR1");
        assertEquals(2, model.countExpressions(), "Model should contain two expressions after second add");
    }

    @Test
    void testAddExpressionIsRegisteredInModelCollections() {
        // name EXPR0
        Expression exprA = model.addExpression();
        // name EXPR1
        Expression exprB = model.addExpression();
        // Retrieval by name
        assertSame(exprA, model.getExpression("EXPR0"), "Expression retrieved by name should be the same instance");
        assertSame(exprB, model.getExpression("EXPR1"), "Expression retrieved by name should be the same instance");
        // Retrieval via the stream of expressions
        Set<String> namesFromStream = model.expressions().map(Expression::getName).collect(Collectors.toSet());
        assertTrue(namesFromStream.containsAll(Set.of("EXPR0", "EXPR1")), "Stream of expressions must contain the autogenerated names");
        assertEquals(2, namesFromStream.size(), "Exactly two expressions should be present in the stream");
    }

    @Test
    void testAddExpressionDoesNotAffectVariableCount() {
        // No variables initially
        assertEquals(0, model.countVariables(), "Model should start with zero variables");
        // Add an expression
        model.addExpression();
        // Variable count must stay unchanged
        assertEquals(0, model.countVariables(), "Adding an expression must not create variables");
    }

    @Test
    void testAddExpressionCanBeUsedInAFullModelSolve() {
        // Build a tiny optimisation problem to ensure the expression is functional
        Variable x = model.addVariable().lower(0).upper(10).weight(1);
        // force x == 5
        Expression expr = model.addExpression().lower(5).upper(5);
        // 1 * x = 5
        expr.set(x, 1);
        // Solve – the optimiser should respect the constraint
        Optimisation.Result result = model.minimise();
        assertTrue(model.validate(result), "Result should be valid for the constructed model");
        assertEquals(Optimisation.State.OPTIMAL, result.getState(), "Model should be solved optimally");
        assertEquals(5, result.doubleValue(0), 1e-12, "Variable x should take the value 5");
    }

    @Test
    void testNamingAfterCustomAddition() {
        // First auto‑generated expression
        // EXPR0
        Expression auto0 = model.addExpression();
        assertEquals("EXPR0", auto0.getName());
        // Add a custom expression with an explicit name
        Expression custom = model.addExpression("CUSTOM");
        assertEquals("CUSTOM", custom.getName());
        // Next auto‑generated name should be based on current map size (2) → EXPR2
        Expression auto2 = model.addExpression();
        assertEquals("EXPR2", auto2.getName(), "Auto‑generated name must follow the raw map size");
        assertEquals(3, model.countExpressions(), "Map size should be 3 after the third addition");
        assertSame(auto2, model.getExpression("EXPR2"));
    }

    @Test
    void testNamingAfterRemovalReusesSizeBasedName() {
        // Add three expressions: EXPR0, EXPR1, EXPR2
        // EXPR0
        Expression e0 = model.addExpression();
        // EXPR1
        Expression e1 = model.addExpression();
        // EXPR2
        Expression e2 = model.addExpression();
        // Remove the middle one
        model.removeExpression("EXPR1");
        assertNull(model.getExpression("EXPR1"), "Removed expression must no longer be retrievable");
        assertEquals(2, model.countExpressions(), "Map size after removal should be 2");
        // Next auto‑generated name uses the current size (2) → EXPR2
        Expression eNew = model.addExpression();
        assertEquals("EXPR2", eNew.getName(), "Name after removal should be based on current size");
        assertEquals(3, model.countExpressions(), "Map size should increase to 3 after re‑adding");
        assertNotSame(e2, eNew, "The newly created expression must be a different instance");
    }

    @Test
    void testDuplicateNameHandlingWhenCustomExpressionCollides() {
        // Add a custom expression that occupies the name the next auto‑generation would use
        // map size = 1
        Expression custom = model.addExpression("EXPR1");
        assertEquals("EXPR1", custom.getName());
        // The next call to addExpression() will try to create "EXPR1" again → should fail
        assertThrows(RuntimeException.class, () -> model.addExpression(), "Adding an expression with a duplicate auto‑generated name must throw");
    }

    @Test
    void testDuplicateNameHandlingAfterMultipleAutoAndCustomAdds() {
        // Three auto‑generated expressions: EXPR0, EXPR1, EXPR2
        // EXPR0
        model.addExpression();
        // EXPR1
        model.addExpression();
        // EXPR2
        model.addExpression();
        // Add a custom expression that uses the name that will be generated next (EXPR4)
        Expression custom = model.addExpression("EXPR4");
        assertEquals("EXPR4", custom.getName());
        // At this point the map size is 4, so the next auto‑generated name will be "EXPR4" again → conflict
        assertThrows(RuntimeException.class, () -> model.addExpression(), "Duplicate auto‑generated name after custom addition must raise an exception");
    }

    @ParameterizedTest
    @ValueSource(ints = { 10 })
    void testMultipleSequentialAdditions(int count) {
        // Add 'count' expressions and verify naming and retrieval
        for (int i = 0; i < count; i++) {
            Expression expr = model.addExpression();
            String expectedName = "EXPR" + i;
            assertEquals(expectedName, expr.getName(), () -> "Expression " + i + " should be named " + expectedName);
            assertSame(expr, model.getExpression(expectedName), () -> "Retrieved instance for " + expectedName + " must be identical");
        }
        assertEquals(count, model.countExpressions(), "Model must contain exactly " + count + " expressions after sequential adds");
    }

    @Test
    void testMixedCustomAndAutoNames() {
        // Add three auto‑generated expressions: EXPR0, EXPR1, EXPR2
        // EXPR0
        model.addExpression();
        // EXPR1
        model.addExpression();
        // EXPR2
        model.addExpression();
        // Add a custom expression with a higher numeric suffix
        Expression custom = model.addExpression("EXPR5");
        assertEquals("EXPR5", custom.getName());
        // Current map size = 4, next auto‑generated name = EXPR4
        Expression auto = model.addExpression();
        assertEquals("EXPR4", auto.getName(), "Auto‑generated name must follow raw map size, even if lower than an existing custom suffix");
        assertEquals(5, model.countExpressions(), "Map size should be 5 after mixed additions");
        assertTrue(model.getExpressions().stream().anyMatch(e -> "EXPR5".equals(e.getName())), "Custom expression EXPR5 must still be present");
    }

    @Test
    void testAddExpressionAfterModelDisposal() {
        model.dispose();
        assertThrows(RuntimeException.class, () -> model.addExpression(), "Calling addExpression() on a disposed model must raise an exception");
    }

    @Test
    void testDuplicateNameCausedByPriorCustomAdditionAtStart() {
        // Add a custom expression that occupies the first auto‑generated name
        Expression custom = model.addExpression("EXPR0");
        assertEquals("EXPR0", custom.getName());
        // Now any call to addExpression() will try to generate "EXPR0" again → error
        assertThrows(RuntimeException.class, () -> model.addExpression(), "Duplicate name caused by prior custom addition should raise an exception");
    }

    @Test
    void testMapSizeOverflowSimulation() throws Exception {
        // Simulate a map whose size() reports Integer.MAX_VALUE and whose put throws on overflow
        Map<String, Expression> overflowMap = new HashMap<String, Expression>() {

            @Override
            public int size() {
                return Integer.MAX_VALUE;
            }

            @Override
            public Expression put(String key, Expression value) {
                throw new ArithmeticException("Simulated map overflow");
            }
        };
        // Inject the custom map via reflection
        Field field = ExpressionsBasedModel.class.getDeclaredField("myExpressions");
        field.setAccessible(true);
        field.set(model, overflowMap);
        // Adding an expression should now fail with ArithmeticException
        assertThrows(ArithmeticException.class, () -> model.addExpression(), "When the internal map size overflows, addExpression() must propagate an ArithmeticException");
    }
}
