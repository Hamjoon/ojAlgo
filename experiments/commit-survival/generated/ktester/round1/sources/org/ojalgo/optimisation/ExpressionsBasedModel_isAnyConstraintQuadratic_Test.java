    private static Stream<Arguments> earlyTrueProvider() {
        return Stream.of(// First qualifies, later ignored – true
        Arguments.of(mapOfSpec("e1", new ExprSpec(true, false, true), "e2", new ExprSpec(true, false, false), "e3", new ExprSpec(false, false, true)), true, "First expression already makes result true."), // First qualifies, later redundant or qualifying – true
        Arguments.of(mapOfSpec("e1", new ExprSpec(true, false, true), "e2", new ExprSpec(true, true, true), "e3", new ExprSpec(true, false, true)), true, "First qualifying constraint should dominate."));
    }

    /**
     * Creates a Mockito mock of {@link Expression} that behaves according to the supplied {@link ExprSpec}.
     */
    private static Expression mockExpression(ExprSpec spec) {
        return (Expression) Proxy.newProxyInstance(Expression.class.getClassLoader(), new Class<?>[] { Expression.class }, (proxy, method, args) -> {
            switch(method.getName()) {
                case "isConstraint":
                    return spec.constraint;
                case "isRedundant":
                    return spec.redundant;
                case "isAnyQuadraticFactorNonZero":
                    return spec.anyQuadratic;
                default:
                    // Return sensible defaults for other methods
                    Class<?> ret = method.getReturnType();
                    if (ret.isPrimitive()) {
                        if (ret == boolean.class)
                            return false;
                        if (ret == int.class)
                            return 0;
                        if (ret == long.class)
                            return 0L;
                        if (ret == double.class)
                            return 0.0;
                        if (ret == float.class)
                            return 0f;
                        if (ret == byte.class)
                            return (byte) 0;
                        if (ret == short.class)
                            return (short) 0;
                        if (ret == char.class)
                            return '\0';
                    }
                    return null;
            }
        });
    }

    /**
     * Creates a proxy that throws the given exception when the specified method is invoked.
     */
    private static Expression exceptionExpression(ExprSpec baseSpec, String methodToThrow, RuntimeException ex) {
        return (Expression) Proxy.newProxyInstance(Expression.class.getClassLoader(), new Class<?>[] { Expression.class }, (proxy, method, args) -> {
            if (method.getName().equals(methodToThrow)) {
                throw ex;
            }
            // Normal behaviour for the three methods we care about
            switch(method.getName()) {
                case "isConstraint":
                    return baseSpec.constraint;
                case "isRedundant":
                    return baseSpec.redundant;
                case "isAnyQuadraticFactorNonZero":
                    return baseSpec.anyQuadratic;
                default:
                    // sensible defaults
                    Class<?> ret = method.getReturnType();
                    if (ret.isPrimitive()) {
                        if (ret == boolean.class)
                            return false;
                        if (ret == int.class)
                            return 0;
                        if (ret == long.class)
                            return 0L;
                        if (ret == double.class)
                            return 0.0;
                        if (ret == float.class)
                            return 0f;
                        if (ret == byte.class)
                            return (byte) 0;
                        if (ret == short.class)
                            return (short) 0;
                        if (ret == char.class)
                            return '\0';
                    }
                    return null;
            }
        });
    }

    /**
     * No constraints – the method must return {@code false}.
     */
    @Test
    void testNoConstraints() {
        assertFalse(model.isAnyConstraintQuadratic(), "Model without constraints should report no quadratic constraints.");
    }

    /**
     * Linear constraint only – the method must return {@code false}.
     */
    @Test
    void testLinearConstraintOnly() {
        Expression linear = model.newExpression("linear").lower(BigDecimal.valueOf(5)).upper(BigDecimal.valueOf(5));
        linear.set(x, BigMath.ONE);
        linear.set(y, BigMath.TWO);
        assertFalse(model.isAnyConstraintQuadratic(), "Model with only linear constraints should report no quadratic constraints.");
    }

    /**
     * Quadratic constraint – the method must return {@code true}.
     */
    @Test
    void testQuadraticConstraint() {
        Expression quad = model.newExpression("quad").upper(BigDecimal.valueOf(20));
        quad.quadraticFactor(x, x, BigMath.ONE);
        quad.set(y, BigMath.ONE);
        assertTrue(model.isAnyConstraintQuadratic(), "Model with a quadratic constraint should report true.");
    }

    /**
     * Quadratic objective should NOT be considered a quadratic constraint.
     */
    @Test
    void testQuadraticObjectiveOnly() {
        Expression obj = model.objective();
        obj.weight(BigMath.ONE);
        obj.quadraticFactor(x, y, BigMath.ONE);
        assertFalse(model.isAnyConstraintQuadratic(), "Quadratic terms in the objective must not affect the constraint check.");
    }

    /**
     * A quadratic constraint that is marked redundant should still be detected.
     */
    @Test
    void testRedundantQuadraticConstraint() {
        Expression quad = model.newExpression("redundantQuad").lower(BigDecimal.ZERO).upper(BigDecimal.ZERO);
        quad.quadraticFactor(x, x, BigMath.ONE);
        assertTrue(model.isAnyConstraintQuadratic(), "Even a redundant quadratic constraint must be reported as present.");
    }

