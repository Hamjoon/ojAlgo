    private ExpressionsBasedModel model;

    private Variable x;

    private Variable y;

    /**
     * Simple specification used to drive the behaviour of mocked {@link Expression}s.
     */
    private static class ExprSpec {

        final boolean constraint;

        final boolean redundant;

        final boolean anyQuadratic;

        final Class<? extends RuntimeException> exception;

        ExprSpec(boolean constraint, boolean redundant, boolean anyQuadratic) {
            this(constraint, redundant, anyQuadratic, null);
        }

        ExprSpec(Class<? extends RuntimeException> exception) {
            this(false, false, false, exception);
        }

        ExprSpec(boolean constraint, boolean redundant, boolean anyQuadratic, Class<? extends RuntimeException> exception) {
            this.constraint = constraint;
            this.redundant = redundant;
            this.anyQuadratic = anyQuadratic;
            this.exception = exception;
        }
    }

    @BeforeEach
    void setupBeforeEach() {
        model = new ExpressionsBasedModel();
        x = model.newVariable("x").lower(BigDecimal.ZERO).upper(BigDecimal.valueOf(10));
        y = model.newVariable("y").lower(BigDecimal.ZERO).upper(BigDecimal.valueOf(10));
    }

    /**
     * Helper that injects a map into the private {@code myExpressions} field of the model.
     */
    private void injectExpressions(Map<String, Expression> map) {
        try {
            Field f = ExpressionsBasedModel.class.getDeclaredField("myExpressions");
            f.setAccessible(true);
            f.set(model, map);
        } catch (Exception e) {
            throw new RuntimeException(e);
        }
    }

    private static Stream<Arguments> basicScenarioProvider() {
        return Stream.of(// No expressions – expect false
        Arguments.of(Collections.emptyMap(), false, "Model contains no expressions."), // Non‑constraint with quadratic factor – false
        Arguments.of(Map.of("e1", mockExpression(new ExprSpec(false, false, true))), false, "Non‑constraint expression with quadratic factor must be ignored."), // Redundant constraint with quadratic factor – false
        Arguments.of(Map.of("e1", mockExpression(new ExprSpec(true, true, true))), false, "Redundant constraint must be ignored."), // Non‑redundant constraint, no quadratic – false
        Arguments.of(Map.of("e1", mockExpression(new ExprSpec(true, false, false))), false, "Constraint without quadratic factor must return false."), // Non‑redundant constraint with quadratic – true
        Arguments.of(Map.of("e1", mockExpression(new ExprSpec(true, false, true))), true, "Constraint with quadratic factor must return true."));
    }

    /**
     * -----------------------------------------------------------------------
     *  MIXED COLLECTION SCENARIOS (JSON “multiple expressions mixed” group)
     *  -----------------------------------------------------------------------
     */
    private static Stream<Arguments> mixedCollectionProvider() {
        return Stream.of(// First qualifies, second does not – true
        Arguments.of(mapOfSpec("e1", new ExprSpec(true, false, true), "e2", new ExprSpec(true, false, false)), true, "First expression qualifies, second does not."), // Both ignored (first redundant, second non‑constraint) – false
        Arguments.of(mapOfSpec("e1", new ExprSpec(true, true, true), "e2", new ExprSpec(false, false, true)), false, "Both expressions ignored."), // All constraints, non‑redundant, no quadratic – false
        Arguments.of(mapOfSpec("e1", new ExprSpec(true, false, false), "e2", new ExprSpec(true, false, false)), false, "All constraints have zero quadratic factors."), // Mixed non‑constraint and qualifying constraint – true
        Arguments.of(mapOfSpec("e1", new ExprSpec(false, false, true), "e2", new ExprSpec(true, false, true)), true, "Second expression qualifies."), // Two qualifying constraints – true (idempotent)
        Arguments.of(mapOfSpec("e1", new ExprSpec(true, false, true), "e2", new ExprSpec(true, false, true)), true, "Both expressions qualify."));
    }

